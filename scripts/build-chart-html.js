#!/usr/bin/env node
/**
 * Builds src/assets/chartHtml.generated.ts — the Trade screen's WebView page
 * with TradingView Lightweight Charts INLINED (no CDN, works offline).
 *
 * Run after upgrading lightweight-charts:  npm run chart:html
 *
 * The page listens for postMessage({ type: 'candles', candles, up, down })
 * from React Native and posts { type: 'ready' } back once loaded.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const lib = fs.readFileSync(
  path.join(root, 'node_modules/lightweight-charts/dist/lightweight-charts.standalone.production.js'),
  'utf8',
);
const version = require(path.join(root, 'node_modules/lightweight-charts/package.json')).version;

const page = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html,body,#c{margin:0;height:100%;background:#050505;overflow:hidden}</style>
</head><body><div id="c"></div>
<script>${lib.replace(/<\/script>/g, '<\\/script>')}</script>
<script>
(function () {
  var LC = window.LightweightCharts;
  var el = document.getElementById('c');
  var chart = LC.createChart(el, {
    autoSize: true,
    layout: { background: { type: 'solid', color: '#050505' }, textColor: '#B4B4B4', fontSize: 11, attributionLogo: true },
    grid: { vertLines: { visible: false }, horzLines: { visible: false } },
    rightPriceScale: { borderVisible: false },
    timeScale: { borderVisible: false, timeVisible: true, secondsVisible: false },
    crosshair: { mode: 0 },
    handleScale: true,
    handleScroll: true
  });
  var series = chart.addSeries(LC.CandlestickSeries, {
    upColor: '#22C55E', downColor: '#EF4444', borderVisible: false,
    wickUpColor: '#22C55E', wickDownColor: '#EF4444'
  });
  function post(o) { window.ReactNativeWebView && window.ReactNativeWebView.postMessage(JSON.stringify(o)); }
  window.onerror = function (msg) { post({ type: 'error', message: String(msg) }); };
  function onMsg(e) {
    var m; try { m = JSON.parse(e.data); } catch (_) { return; }
    if (m.type === 'candles') {
      try {
        if (m.up) series.applyOptions({ upColor: m.up, wickUpColor: m.up });
        if (m.down) series.applyOptions({ downColor: m.down, wickDownColor: m.down });
        // Hedera tokens trade at fractions of a cent: size the price scale's
        // precision to the data (4 significant digits) instead of 2 dp.
        var last = (m.candles && m.candles.length) ? m.candles[m.candles.length - 1].close : 1;
        var precision = last >= 1 ? 2 : Math.min(10, Math.max(2, 3 - Math.floor(Math.log10(last))));
        series.applyOptions({ priceFormat: { type: 'price', precision: precision, minMove: Math.pow(10, -precision) } });
        series.setData(m.candles || []);
        chart.timeScale().fitContent();
        post({ type: 'drawn', count: (m.candles || []).length });
      } catch (err) {
        post({ type: 'error', message: String(err && err.message || err) });
      }
    }
  }
  window.addEventListener('message', onMsg);
  document.addEventListener('message', onMsg); // Android WebView
  window.ReactNativeWebView && window.ReactNativeWebView.postMessage(JSON.stringify({ type: 'ready' }));
})();
</script></body></html>`;

const out = `// GENERATED by scripts/build-chart-html.js from lightweight-charts@${version} — do not edit.
// Regenerate with: npm run chart:html
/* eslint-disable */
export const CHART_HTML: string = ${JSON.stringify(page)};
`;
fs.mkdirSync(path.join(root, 'src/assets'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/assets/chartHtml.generated.ts'), out);
console.log(`Wrote src/assets/chartHtml.generated.ts (lightweight-charts ${version}, ${(out.length / 1024).toFixed(0)} KB)`);
